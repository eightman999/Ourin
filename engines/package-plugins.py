#!/usr/bin/env python3
"""Build local, self-contained Ourin SHIORI .plugin bundles.

This command does not publish packages or install them in a user's profile.
License scopes from the pinned upstream manifests remain attached to each plugin.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import plistlib
import shutil
import subprocess
import sys
import zipfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
NAMES = {
    'kawari': '華和梨 (KAWARI)', 'aosora': 'Aosora', 'miyojs': 'MiyoJS',
    'sanajk': 'SanaJK', 'sana': 'Sana', 'phiori': 'phiori', 'aktk': 'aktk',
    'dktrtk': 'dktrtk', 'krht': 'krht', 'emo-rs': 'emo-rs (LuaJIT)',
    'emo-rs-lua54': 'emo-rs (Lua 5.4)', 'dnproxy': 'D.N.Proxy',
    'kanahebi': 'Kanahebi', 'rosalind': 'Rosalind',
}


def relative(value: str, engine_id: str) -> str:
    prefix = engine_id + '/'
    result = value[len(prefix):] if value.startswith(prefix) else value
    path = Path(result)
    if path.is_absolute() or '..' in path.parts or not result:
        raise ValueError('Invalid engine-relative path: ' + value)
    return result


def package(stage: Path, entry: dict, output: Path, archive: bool) -> dict:
    engine_id = entry['id']
    if not engine_id or any(c not in 'abcdefghijklmnopqrstuvwxyz0123456789_-' for c in engine_id):
        raise ValueError('Invalid engine id')
    source = stage / engine_id
    if not source.is_dir():
        raise FileNotFoundError(source)
    destination = output / 'packages' / (engine_id + '.plugin')
    if destination.exists():
        # This directory is exclusively generated by this command.
        if not (destination / 'Contents/Resources/engine.json').is_file():
            raise ValueError('Refusing to replace a directory without engine.json: ' + str(destination))
        shutil.rmtree(destination)
    payload = destination / 'Contents/Resources'
    shutil.copytree(source, payload, symlinks=True)
    # The native stager uses ENGINE.json for its build record. On the usual
    # case-insensitive macOS volume, writing engine.json would otherwise retain
    # that uppercase filename in the ZIP instead of creating the plugin manifest.
    for existing in payload.iterdir():
        if existing.name.lower() == 'engine.json':
            existing.rename(payload / 'STAGED_ENGINE.json')
    descriptor = {key: entry[key] for key in (
        'kind', 'arguments', 'environment', 'charset', 'moduleNames', 'markers',
        'commandHints', 'architectures', 'licenseScope', 'limitations', 'abi', 'launchTimeout', 'minimumOSVersion'
    ) if key in entry}
    descriptor.update(schema=1, id=engine_id, name=entry.get('name', NAMES.get(engine_id, engine_id)))
    descriptor.setdefault('moduleNames', [])
    descriptor.setdefault('arguments', [])
    for key in ('module', 'executable'):
        if entry.get(key):
            descriptor[key] = relative(entry[key], engine_id)
    if engine_id == 'kawari':
        descriptor['moduleNames'] = ['kawari.dll', 'kosui.dll', 'shiori.dll']
        descriptor['markers'] = ['kawarirc.ini', 'kawarirc.kis']
    if engine_id == 'rosalind':
        descriptor['moduleNames'] = ['rosalind.dll', 'SHIOLINK.dll']
        descriptor['markers'] = ['Ghost.csx']
    if entry['kind'] == 'development-sample':
        descriptor['moduleNames'] = []
        descriptor['limitations'] = '開発用のコンパイル済みサンプルです。任意のWindows DLLの代替にはなりません。'
    if descriptor.get('licenseScope') in ('unconfirmed', 'local-use-only'):
        descriptor['limitations'] = (descriptor.get('limitations', '') + ' ローカル利用用。再配布条件は上流の通知を確認してください。').strip()
    info = {'CFBundleIdentifier': 'com.furinlab.ourin.shiori.' + engine_id.replace('_', '-'),
            'CFBundleName': descriptor['name'], 'CFBundlePackageType': 'BNDL',
            'CFBundleVersion': '1', 'CFBundleShortVersionString': '1.0',
            'OurinShioriEnginePackageVersion': 1}
    if descriptor.get('minimumOSVersion'):
        info['LSMinimumSystemVersion'] = descriptor['minimumOSVersion']
    (destination / 'Contents/Info.plist').write_bytes(plistlib.dumps(info))
    (payload / 'engine.json').write_text(json.dumps(descriptor, ensure_ascii=False, indent=2) + '\n')
    (payload / 'SOURCE_MANIFEST.json').write_text(json.dumps(entry, ensure_ascii=False, indent=2) + '\n')
    (payload / 'INSTALL.txt').write_text(
        'Ourinの「プラグインを探す・管理…」→「SHIORIエンジン」→「プラグインを導入…」から、この.pluginを選択します。展開は不要です。\n'
        '導入後に対象ゴーストを再起動してください。元のゴースト辞書やdescript.txtを書き換える必要はありません。\n'
        '上流のLICENSE/NOTICEとengine.jsonの制限を確認してください。この生成コマンドは外部へ公開しません。\n', encoding='utf-8')
    resolved = destination.resolve()
    for path in destination.rglob('*'):
        if path.is_symlink() and not path.resolve().is_relative_to(resolved):
            raise ValueError('Plugin contains an external symlink: ' + str(path))
    digest, size = hashlib.sha256(), 0
    for path in sorted(destination.rglob('*')):
        digest.update(str(path.relative_to(destination)).encode() + b'\0')
        if path.is_symlink():
            digest.update(b'link\0' + os.readlink(path).encode() + b'\0')
        elif path.is_file():
            digest.update(b'file\0' + str(path.stat().st_mode & 0o777).encode() + b'\0')
            with path.open('rb') as stream:
                while chunk := stream.read(1024 * 1024):
                    size += len(chunk)
                    digest.update(chunk)
    result = {'id': engine_id, 'name': descriptor['name'], 'plugin': str(destination), 'folder': str(destination),
              'format': 'plugin', 'bytes': size, 'sha256': digest.hexdigest(),
              'kind': descriptor['kind'], 'licenseScope': descriptor.get('licenseScope', 'unconfirmed')}
    if archive:
        archive_path = output / 'archives' / (engine_id + '.plugin.zip')
        archive_path.parent.mkdir(parents=True, exist_ok=True)
        # Dereference in-package symlinks so ZIP import does not require symlink extraction.
        with zipfile.ZipFile(archive_path, 'w', zipfile.ZIP_DEFLATED, compresslevel=4) as stream:
            for path in sorted(destination.rglob('*')):
                if path.is_file():
                    stream.write(path, str(Path(destination.name) / path.relative_to(destination)))
        result.update(archive=str(archive_path), archive_bytes=archive_path.stat().st_size,
                      archive_sha256=hashlib.sha256(archive_path.read_bytes()).hexdigest())
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build/engine-plugins')
    parser.add_argument('--stage', action='append', type=Path, help='Reuse an already staged group; repeatable')
    parser.add_argument('--group', action='append', choices=['native', 'script', 'dotnet', 'yaya', 'nashi'])
    parser.add_argument('--archives', action='store_true', help='Also create ZIPs for transferring the .plugin bundles')
    parser.add_argument('--no-archives', action='store_true', help=argparse.SUPPRESS)
    args = parser.parse_args()
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    stages = list(args.stage or [])
    if not stages:
        for group in args.group or ['native', 'script', 'dotnet', 'yaya', 'nashi']:
            stage = output / 'staging' / group
            script = {'native': 'package-native.py', 'script': 'package-script-engines.py',
                      'dotnet': 'package-dotnet-engines.py', 'yaya': 'yaya/package.py',
                      'nashi': 'nashi/package.py'}[group]
            command = [sys.executable, str(HERE / script), '--destination', str(stage)]
            if group in ('native', 'yaya'): command.append('--build-missing')
            subprocess.run(command, check=True)
            stages.append(stage)
    packages, seen = [], set()
    for stage in stages:
        manifests = sorted(stage.glob('*-manifest.json'))
        if not manifests:
            raise ValueError('No group manifest in ' + str(stage))
        for manifest in manifests:
            for entry in json.loads(manifest.read_text()):
                if entry['id'] in seen: raise ValueError('Duplicate engine: ' + entry['id'])
                seen.add(entry['id'])
                packages.append(package(stage, entry, output, args.archives and not args.no_archives))
    (output / 'packages.json').write_text(json.dumps({'schema': 1, 'packages': packages}, ensure_ascii=False, indent=2) + '\n')
    print(f'Created {len(packages)} local SHIORI plugin packages: {output}')


if __name__ == '__main__':
    main()
